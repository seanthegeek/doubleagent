// The package once wrote JSON with its own encoder and float formatter.
// These tables hold what they gave for generated values (floats across the
// exponent range with their neighbours, every ASCII character and a few
// others inside a string), and the tests check that the shared encoder now
// used gives the same text.

func TestFloatsAreWrittenAsTheOwnEncoderWroteThem(t *testing.T) {
	for _, test := range floatCases {
		value := Value{kind: KindFloat, float: test.number}
		if got := CompactJSON(value); got != test.want {
			t.Errorf("CompactJSON(%v) = %q, want %q", test.number, got, test.want)
		}
		if got := SettingText(value); got != test.want {
			t.Errorf("SettingText(%v) = %q, want %q", test.number, got, test.want)
		}
	}
}

func TestStringsAreEscapedAsTheOwnEncoderEscapedThem(t *testing.T) {
	for _, test := range textCases {
		t.Run(strconv.QuoteToASCII(test.text)+" is escaped as before", func(t *testing.T) {
			value := Value{kind: KindArray, items: []Value{{kind: KindString, text: test.text}}}
			if got := CompactJSON(value); got != test.want {
				t.Errorf("CompactJSON = %q, want %q", got, test.want)
			}
		})
	}
}

func TestTablesAreWrittenWithSortedKeysAsBefore(t *testing.T) {
	nested := &Table{}
	for i, key := range []string{"z", "a", "é", "aa", "A", "", "\u2028", "😀", "ﬀ", "a b", "\x7f", "\x01"} {
		nested.set(key, Value{kind: KindInteger, integer: int64(i)})
	}
	outer := &Table{}
	outer.set("z", Value{kind: KindTable, table: nested})
	outer.set("a", Value{kind: KindArray, items: []Value{{kind: KindLocalDate, text: "1979-05-27"},
		{kind: KindBoolean, boolean: true}, {kind: KindInteger, integer: math.MinInt64}}})
	outer.set("m", Value{kind: KindTable, table: &Table{}})
	want := "{\"a\":[\"1979-05-27\",true,-9223372036854775808],\"m\":{},\"z\":{\"\":5,\"\\u0001\":11," +
		"\"A\":4,\"a\":1,\"a b\":9,\"aa\":3,\"z\":0,\"\x7f\":10,\"é\":2,\"\u2028\":6,\"ﬀ\":8,\"😀\":7}}"
	if got := SettingText(Value{kind: KindTable, table: outer}); got != want {
		t.Errorf("SettingText = %q, want %q", got, want)
	}
}

