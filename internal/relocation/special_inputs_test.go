func TestBoundedNamesInShellAndPowerShellText(t *testing.T) {
	t.Parallel()
	names := []string{"CODEX_HOME", "ENV", "CLAUDE_CONFIG_DIR"}
	for index, test := range boundedNamesCases {
		for _, powerShell := range []bool{false, true} {
			want := test.shell
			if powerShell {
				want = test.powerShell
			}
			hits, err := boundedNames(strings.NewReader(test.input), names, powerShell)
			var got strings.Builder
			for _, hit := range hits {
				got.WriteString(strconv.Itoa(hit.Line) + "|" + hit.Name + "\n")
			}
			if err != nil || got.String() != want {
				t.Errorf("case %d %q, PowerShell %v:\ngot  %q\nwant %q", index, test.input,
					powerShell, got.String(), want)
			}
		}
	}
}

