// refusedCases are values the Python analyzer read, or crashed on, that
// are refused here: forms only its date parser's leniency allowed.
func refusedCases() []string {
	return []string{
		"2026-10-01t09:30", "2026-10-01_09:30", "2026-10-01 +02:00", // other separators
		"2026-W40-1+02",          // an offset straight after a date
		"2026-10-01T09:30:15,25", // a comma before the fraction
		"2026-10-01T24:00",       // the midnight ending a day
		"2026- 1-01", "1_00-01-01", "2026-10-01T09:3", "2026-10-01T09:30:1",
		"2026-10-01T09:30+05:3",                  // fields not of two or four digits
		"\u0663d", "2 wee\u212as", "45 M\u0130N", // non-ASCII digits and letters
		"9999-12-31T23:30-01:00", "0001-01-01T00:30+01:00", // past the years 1 to 9999
	}
}

func TestParseBound(t *testing.T) {
	for _, test := range acceptedCases() {
		t.Run("reads "+test.text, func(t *testing.T) {
			since, err := ParseBound(test.text, false, testNow())
			if err != nil || since != test.since {
				t.Errorf("since = %q, %v; want %q", since, err, test.since)
			}
			until, err := ParseBound(test.text, true, testNow())
			if err != nil || until != test.until {
				t.Errorf("until = %q, %v; want %q", until, err, test.until)
			}
		})
	}
	for _, text := range append(rejectedCases(), refusedCases()...) {
		t.Run("refuses "+text[:min(len(text), 40)], func(t *testing.T) {
			for _, upper := range []bool{false, true} {
				bound, err := ParseBound(text, upper, testNow())
				var boundErr *BoundError
				if !errors.As(err, &boundErr) {
					t.Fatalf("ParseBound(upper %v) = %q, %v; want a BoundError", upper, bound, err)
				}
				if !strings.HasSuffix(err.Error(), "; "+FormsHelp) {
					t.Errorf("message %q does not end with the forms", err)
				}
			}
		})
	}
}

func TestUntilAtTheEndOfTheYear9999(t *testing.T) {
	// The Python analyzer failed with an overflow here, computing the start
	// of the following period before taking a millisecond off.
	for _, text := range []string{"9999", "9999-12", "9999-12-31", "9999-12-31T23:59"} {
		until, err := ParseBound(text, true, testNow())
		if err != nil || until != "9999-12-31T23:59:59.999Z" {
			t.Errorf("ParseBound(%q, until) = %q, %v", text, until, err)
		}
	}
}

func TestBoundErrorMessages(t *testing.T) {
	tests := []struct{ text, reason string }{
		{"2026-13-01", "cannot read \"2026-13-01\" as a time (month must be in 1..12, not 13)"},
		{"2026-02-29", "cannot read \"2026-02-29\" as a time (day must be in 1..28 for 2026-02, " +
			"not 29)"},
		{"2026-10-01T25:00", "cannot read \"2026-10-01T25:00\" as a time (hour must be in " +
			"0..23, not 25)"},
		{"2026-13-01T09:30+24:00", "cannot read \"2026-13-01T09:30+24:00\" as a time (offset " +
			"hours must be in 0..23, not 24)"},
		{"2026-10-01T09:30+02:60", "cannot read \"2026-10-01T09:30+02:60\" as a time (offset " +
			"minutes must be in 0..59, not 60)"},
		{"2026-W54-1", "cannot read \"2026-W54-1\" as a time (week must be in 1..53, not 54)"},
		{"2026-366", "cannot read \"2026-366\" as a time (ordinal day must be in 1..365 for " +
			"2026, not 366)"},
		{"9999-W52-7", "cannot read \"9999-W52-7\" as a time (year must be in 1..9999, not " +
			"10000)"},
		{"last friday", "cannot read \"last friday\" as a time"},
		{"", "cannot read \"\" as a time"},
		{"99999y", `"99999y" is out of range`},
		{strings.Repeat("9", 20), `"99999999999999999999" is out of range as epoch seconds ` +
			"or milliseconds"},
		{"9999-12-31T23:30-01:00", "cannot read \"9999-12-31T23:30-01:00\" as a time (the " +
			"time is out of range)"},
		{"it's", `cannot read "it's" as a time`},
	}
	for _, test := range tests {
		t.Run(test.text, func(t *testing.T) {
			_, err := ParseBound(test.text, false, testNow())
			if want := test.reason + "; " + FormsHelp; err == nil || err.Error() != want {
				t.Errorf("error %v\nwant %s", err, want)
			}
		})
	}
}
